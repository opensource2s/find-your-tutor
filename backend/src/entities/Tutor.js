const { EntitySchema } = require("typeorm");

module.exports = new EntitySchema({
  name: "Tutor",
  tableName: "tutors",
  columns: {
    id: { type: "uuid", primary: true, generated: "uuid" },
    auth0_id: { type: "varchar", length: 255, nullable: true, unique: true },
    name: { type: "varchar", length: 100 },
    email: { type: "varchar", length: 150, nullable: true, unique: true },
    mobile: { type: "varchar", length: 20, nullable: true, unique: true },
    password_hash: { type: "text", nullable: true },
    title: { type: "varchar", length: 150, nullable: true },
    bio: { type: "text", nullable: true },
    tutor_type: { type: "varchar", length: 50, nullable: true },
    skills: { type: "text", array: true, nullable: true },
    experience_years: { type: "int", default: 0 },
    hourly_rate: { type: "numeric", precision: 10, scale: 2, nullable: true },
    profile_image: { type: "text", nullable: true },
    country: { type: "varchar", length: 80, nullable: true },
    city: { type: "varchar", length: 80, nullable: true },
    timezone: { type: "varchar", length: 80, default: "Asia/Kolkata" },
    languages: { type: "text", array: true, nullable: true },
    teaching_modes: { type: "text", array: true, nullable: true },
    education: { type: "text", nullable: true },
    certifications: { type: "text", array: true, nullable: true },
    achievements: { type: "text", array: true, nullable: true },
    linkedin_url: { type: "text", nullable: true },
    website_url: { type: "text", nullable: true },
    intro_video_url: { type: "text", nullable: true },
    response_time_hours: { type: "int", default: 24 },
    trial_lesson_available: { type: "boolean", default: false },
    is_accepting_messages: { type: "boolean", default: true },
    short_intro: { type: "varchar", length: 280, nullable: true },
    teaching_philosophy: { type: "text", nullable: true },
    specialties: { type: "text", array: true, nullable: true },
    student_levels: { type: "text", array: true, nullable: true },
    lesson_duration_minutes: { type: "int", array: true, nullable: true },
    currency: { type: "varchar", length: 8, default: "INR" },
    profile_published: { type: "boolean", default: false },
    profile_published_at: { type: "timestamptz", nullable: true },
    last_active_at: { type: "timestamptz", nullable: true },
    id_proof_type: { type: "varchar", length: 50, nullable: true },
    id_proof_url: { type: "text", nullable: true },
    qualification_proof_url: { type: "text", nullable: true },
    verification_status: { type: "varchar", length: 30, default: "not_submitted" },
    verification_notes: { type: "text", nullable: true },
    verified_at: { type: "timestamptz", nullable: true },
    max_students: { type: "int", default: 50 },
    is_verified: { type: "boolean", default: false },
    is_active: { type: "boolean", default: true },
    created_at: { type: "timestamp", createDate: true },
    updated_at: { type: "timestamp", updateDate: true },
  },
});
